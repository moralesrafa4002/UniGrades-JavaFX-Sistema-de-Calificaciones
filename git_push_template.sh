# Fase 6 — Manual de usuario

## Inicio de sesión

Al iniciar la aplicación aparece una pantalla de login. El usuario debe escribir correo y contraseña.

Usuarios de prueba:

- Administrador: `admin@universidad.edu` / `admin123`
- Profesor: `profesor@universidad.edu` / `profe123`
- Alumno: `alumno@universidad.edu` / `alumno123`

## Uso como administrador

El administrador puede entrar a varias pestañas:

- Carreras.
- Materias y configuración.
- Usuarios.
- Grupos e inscripciones.
- Calificaciones.

Debe llenar los campos y presionar el botón correspondiente.

## Uso como profesor

El profesor visualiza los alumnos inscritos en sus grupos. Puede seleccionar un alumno, capturar calificaciones y guardar. El promedio final se calcula automáticamente.

## Uso como alumno

El alumno solo puede consultar sus calificaciones. No tiene permisos de edición.

## Manejo de errores

Si el usuario captura datos incorrectos, el sistema muestra una alerta y evita que la aplicación se cierre inesperadamente.
